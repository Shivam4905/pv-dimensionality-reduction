function T = result_row(Method, LB_days, FH_hours, BestDim, N_params, ...
                        Param_reduction_pct, FilterScore, ...
                        RMSE, nRMSE, R2, NICE1, NICE2, NICE3, NICE_Sigma)
% Fabrique une ligne de resultat au schema commun aux trois familles de
% lignes (references, wrapper, filter). Les colonnes non pertinentes pour une
% famille sont laissees a NaN :
%   - references / wrapper : FilterScore = NaN
%   - filter (geometrique) : RMSE..NICE_Sigma = NaN, FilterScore = S*
% La colonne N_params est la cle de lecture : elle permet de tracer l'erreur
% en fonction du nombre de parametres (impact de la reduction de dimension).
    T = table(string(Method), LB_days, FH_hours, BestDim, N_params, ...
              Param_reduction_pct, FilterScore, ...
              RMSE, nRMSE, R2, NICE1, NICE2, NICE3, NICE_Sigma, ...
        'VariableNames', {'Method', 'LB_days', 'FH_hours', 'BestDim', ...
              'N_params', 'Param_reduction_pct', 'FilterScore', ...
              'RMSE', 'nRMSE', 'R2', 'NICE1', 'NICE2', 'NICE3', 'NICE_Sigma'});
end
